import fs from 'node:fs';
import type { HunterApp } from '../app.js';
import type { OperationProfile, Seed, Entity, Evidence, Relationship, Hypothesis, Lead, MonitoringProbe, ReappearanceLead, SeedType } from '../types.js';
import { canonicalize, detectType, displayLabel } from '../core/canonical.js';
import { HunterError, newId, nowIso, parseJson, uniq } from '../core/util.js';
import { staticUbiquity } from '../engine/noise.js';
import { artifactObservations } from '../collectors/artifact.js';
import { ingestObservations } from '../engine/ingest.js';

const LEGACY_SIMULATED_PROVENANCE = new Set([
  'Automated Ethereum Ledger Trace Worker', 'Automated Headless DOM Harvester', 'Automated Passive DNS Reverse Query Worker',
  'Autonomous Passive DNS Reverse Query Engine', 'Certificate Transparency Historical Query', 'Certificate Transparency Log Ingestion',
  'DOM diff worker inspection snapshot', 'Ethereum JSON-RPC Node Transaction Analyzer', 'Ethereum JSON-RPC transfer event filter logs',
  'HTML Tag & Tracker Extractor', 'Headless DOM analyzer capture worker', 'On-chain RPC Token Flow Tracing Module', 'Passive DNS Sensor Network Query',
  'Passive DNS telemetry feed rotation detection', 'SecurityTrails Passive DNS API v2 query at intake', 'Static JS AST Deobfuscator',
  'crt.sh Transparency Log monitor stream', 'genome_engine_ast_analyzer_v0.4', 'onchain_financial_analyzer_v0.4',
]);
const QUARANTINE_REASON = 'Legacy v0.x simulated observation (generated by the old prototype, not collected from a real source). Quarantined during the v1.0 migration — run a pursuit to collect real evidence, or reinstate it if you entered it yourself.';

export const DEMO_OPERATION_ID = 'op-arctic-drainer';
export const DEMO_HELIOS_ID = 'op-helios-campaign';

const SEED_TYPES: SeedType[] = ['domain', 'wallet', 'ip', 'certificate', 'template_fingerprint', 'identifier', 'artifact'];

export class OperationService {
  constructor(private app: HunterApp) {}

  private codeFor(name: string): string {
    const base = `OP-${name.replace(/^operation\s+/i, '').replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '').toUpperCase().slice(0, 18) || 'NEW'}`;
    let code = base;
    let i = 2;
    while (this.app.store.getOperation(code)) code = `${base}-${i++}`;
    return code;
  }

  create(input: { name: string; initialSeed: string; targetType?: string; summary?: string; isDemo?: boolean; id?: string; code?: string; mainInvestigationId?: string | null; seedLabel?: string; tags?: string[] }): OperationProfile {
    const name = String(input.name ?? '').trim();
    const seedValue = String(input.initialSeed ?? '').trim();
    if (!name || !seedValue) throw new HunterError('VALIDATION', 'name and initialSeed are required');
    const detected = detectType(seedValue);
    const targetType = (input.targetType && input.targetType !== 'auto' ? input.targetType : detected) ?? 'domain';
    const now = nowIso();
    const op: OperationProfile = {
      id: input.id ?? newId('op', 8),
      code: input.code && !this.app.store.getOperation(input.code) ? input.code : this.codeFor(name),
      name,
      targetType,
      initialSeed: canonicalize(seedTypeToEntity(targetType), seedValue) || seedValue,
      status: 'ACTIVE_RECONSTRUCTION',
      summary: input.summary || `Operation seeded with ${seedValue}. Run a pursuit to reconstruct the wider infrastructure.`,
      establishedFacts: [], uncertainties: [], recentChanges: [], evidenceGaps: [], unresolvedQuestions: [], recommendedNextSteps: [],
      createdAt: now, updatedAt: now, isDemo: Boolean(input.isDemo), mainInvestigationId: input.mainInvestigationId ?? null, lastViewedAt: null,
      revision: 0, tags: input.tags ?? [],
    };
    this.app.store.tx(() => {
      this.app.store.insertOperation(op);
      this.addSeedInternal(op.id, { type: targetType, value: seedValue, label: input.seedLabel ?? 'Initial seed' });
      this.app.store.addChange(op.id, 'created', `Operation created from seed ${seedValue}`);
      this.app.store.logAudit(op.id, 'CREATE_OPERATION', `Created operation ${op.name} with seed ${seedValue}`);
    });
    this.app.store.touch(op.id, 'created');
    return this.app.store.getOperation(op.id)!;
  }

  addSeed(operationId: string, input: { type?: string; value: string; label?: string; notes?: string; source?: string }): Seed {
    const op = this.app.store.getOperation(operationId);
    if (!op) throw new HunterError('NOT_FOUND', 'Operation not found', 404);
    if (!input.value) throw new HunterError('VALIDATION', 'value is required');
    const seed = this.app.store.tx(() => this.addSeedInternal(op.id, input));
    this.app.store.logAudit(op.id, 'ADD_SEED', `Added seed ${input.value} (${seed.type})`);
    this.app.store.addChange(op.id, 'seed_added', `New seed: ${input.value}`);
    this.app.store.touch(op.id, 'seed');
    return seed;
  }

  private addSeedInternal(operationId: string, input: { type?: string; value: string; label?: string; notes?: string; source?: string }): Seed {
    const detected = detectType(input.value);
    const type = (input.type && input.type !== 'auto' ? input.type : detected ?? 'domain') as SeedType;
    const entityType = seedTypeToEntity(type);
    const value = canonicalize(entityType, input.value) || input.value.trim();
    const existingSeed = this.app.store.getSeeds(operationId).find(s => canonicalize(seedTypeToEntity(s.type), s.value) === value);
    const seed: Seed = existingSeed ?? { id: newId('seed', 8), operationId, type: SEED_TYPES.includes(type) ? type : (entityType as SeedType), value, label: input.label, addedAt: nowIso(), status: 'pending', notes: input.notes };
    if (!existingSeed) this.app.store.insertSeed({ ...seed, source: input.source ?? 'analyst' });
    const existing = this.app.store.findEntity(operationId, entityType, value) ?? (entityType === 'wallet' ? this.app.store.findEntity(operationId, 'contract', value) : undefined);
    if (existing) {
      this.app.store.updateEntity({ ...existing, isSeed: true, depth: 0 });
    } else {
      const ub = staticUbiquity(entityType, value);
      const entity: Entity = {
        id: newId('ent', 10), operationId, type: entityType as Entity['type'], value, canonical: canonicalize(entityType, value), label: input.label && input.label !== 'Initial seed' ? `${value}` : displayLabel(entityType, value),
        metadata: { seedSource: input.source ?? 'analyst', ...(input.notes ? { notes: input.notes } : {}) }, firstSeen: nowIso(), lastSeen: nowIso(), isActive: true, isSeed: true, depth: 0, ubiquity: ub.ubiquity, tags: ['seed'],
      };
      this.app.store.insertEntity(entity);
    }
    return seed;
  }

  update(operationId: string, updates: Partial<OperationProfile>) {
    const allowed: Partial<OperationProfile> = {};
    for (const key of ['name', 'status', 'summary', 'tags', 'mainInvestigationId'] as const) if (updates[key] !== undefined) (allowed as any)[key] = updates[key];
    const op = this.app.store.updateOperation(operationId, allowed);
    if (!op) throw new HunterError('NOT_FOUND', 'Operation not found', 404);
    this.app.store.touch(operationId, 'updated');
    return op;
  }

  markViewed(operationId: string) {
    const op = this.app.store.getOperation(operationId);
    if (!op) return;
    this.app.store.run('UPDATE operations SET last_viewed_at=? WHERE id=?', nowIso(), op.id);
  }

  /** Analyst-supplied evidence (text, HTML, report excerpt). HTML is fingerprinted automatically. */
  addManualEvidence(operationId: string, input: { source?: string; type?: string; originalObservation: string; rawData?: Record<string, any>; provenance?: string; confidence?: number; relatedEntityIds?: string[]; subjectValue?: string; content?: string; timestamp?: string }) {
    const op = this.app.store.getOperation(operationId);
    if (!op) throw new HunterError('NOT_FOUND', 'Operation not found', 404);
    if (!input.originalObservation) throw new HunterError('VALIDATION', 'originalObservation is required');
    const related = uniq([...(input.relatedEntityIds ?? [])].filter(id => this.app.store.getEntity(id)?.operationId === operationId));
    let subject: Entity | undefined;
    if (input.subjectValue) {
      const t = detectType(input.subjectValue) ?? 'domain';
      subject = this.app.store.findEntity(operationId, t, input.subjectValue);
      if (!subject) {
        this.addSeed(operationId, { value: input.subjectValue, type: t, label: 'Evidence subject', source: 'manual_evidence' });
        subject = this.app.store.findEntity(operationId, t, input.subjectValue);
      }
      if (subject) related.push(subject.id);
    }
    const content = input.content ?? input.rawData?.html ?? input.rawData?.content;
    const ingest = ingestObservations(this.app.store, [{
      kind: input.type || 'manual_import', source: input.source || 'analyst', observedAt: input.timestamp || nowIso(), summary: input.originalObservation,
      raw: { ...(input.rawData ?? {}), ...(content ? { content } : {}) }, confidence: input.confidence ?? 0.9, assertion: 'analyst',
      provenance: input.provenance || 'Analyst manual import', entities: [], relationships: [],
    }], { operationId, collector: 'analyst' });
    const ev = ingest.newEvidence[0] ?? this.app.store.getEvidence(operationId)[0];
    if (ev && related.length) this.app.store.addEvidenceEntities(ev.id, operationId, uniq(related));
    // Page source / scripts are fingerprinted immediately.
    if (subject && typeof content === 'string' && content.length > 200 && /<[a-z!]/i.test(content)) {
      ingestObservations(this.app.store, artifactObservations(subject, content, { source: 'analysis:analyst', provenance: `Fingerprint of analyst-supplied content (evidence ${ev?.id})`, label: 'Analyst-supplied page source' })
        .map(o => ({ ...o, assertion: 'derived' as const })), { operationId, collector: 'internal', subjectDepth: subject.depth ?? 0 });
    }
    this.app.store.logAudit(operationId, 'ADD_EVIDENCE', `Analyst evidence: ${input.originalObservation.slice(0, 120)}`);
    this.app.store.addChange(operationId, 'evidence_added', `Analyst added evidence: ${input.originalObservation.slice(0, 140)}`);
    this.app.store.touch(operationId, 'evidence');
    return ev ? this.app.store.getEvidenceById(ev.id)! : undefined;
  }

  // ------------------------------------------------------------------ demo
  createDemo(opts: { reconstruct?: boolean } = {}): OperationProfile {
    const base = nowIso();
    this.app.store.setMeta(`demo_base:${DEMO_OPERATION_ID}`, base);
    this.app.store.setMeta(`demo_base:${DEMO_HELIOS_ID}`, base);
    for (const id of [DEMO_OPERATION_ID, DEMO_HELIOS_ID]) if (this.app.store.getOperation(id)) this.app.store.deleteOperation(id);
    const helios = this.create({
      id: DEMO_HELIOS_ID, code: 'OP-HELIOS', name: 'Operation Helios (demo)', initialSeed: 'helios-airdrop-bonus.xyz', targetType: 'domain', isDemo: true, tags: ['demo'],
      summary: 'DEMO — synthetic data. A second airdrop-themed drainer campaign used to demonstrate cross-operation intelligence.',
    });
    const arctic = this.create({
      id: DEMO_OPERATION_ID, code: 'OP-ARCTIC-DRAINER', name: 'Operation Arctic Drainer (demo)', initialSeed: 'eth-recovery-claim.top', targetType: 'domain', isDemo: true, tags: ['demo'],
      summary: 'DEMO — synthetic data. One reported phishing domain; Hunter reconstructs the wider operation from it.',
    });
    this.app.store.logAudit(arctic.id, 'DEMO', 'Initialised Operation Hunter v1.0 demonstration world (synthetic data)');
    if (opts.reconstruct === false) return arctic;
    // Start pursuits; the scheduler (or reconstructDemo) drives them.
    this.app.pursuit.start(helios.id, { budgetTotal: 45, maxHops: 3 });
    this.app.pursuit.start(arctic.id, { budgetTotal: 100, maxHops: 5 });
    return arctic;
  }

  /** Build the demo and run both pursuits to completion (used by reset-demo and tests). */
  async resetDemo(): Promise<OperationProfile> {
    this.createDemo({ reconstruct: false });
    // The demo is reproducible: exploration uses a fixed random stream while it is rebuilt.
    const rnd = this.app.allocator.rnd;
    this.app.allocator.seed(2026);
    try {
      await this.app.pursuit.runToCompletion(DEMO_HELIOS_ID, { budgetTotal: 45, maxHops: 3, concurrency: 3 });
      await this.app.pursuit.runToCompletion(DEMO_OPERATION_ID, { budgetTotal: 100, maxHops: 5, concurrency: 3 });
    } finally {
      this.app.allocator.rnd = rnd;
    }
    this.app.analyzer.analyze(DEMO_HELIOS_ID);
    this.app.analyzer.analyze(DEMO_OPERATION_ID);
    return this.app.store.getOperation(DEMO_OPERATION_ID)!;
  }

  // ------------------------------------------------------------------ legacy import
  importLegacyStore(file: string): { operations: number; quarantined: number; skippedDemo: boolean } {
    const raw = parseJson<any>(fs.readFileSync(file, 'utf-8'), null);
    if (!raw || !Array.isArray(raw.operations)) {
      this.app.store.setMeta('legacy_import_done', `invalid:${nowIso()}`);
      return { operations: 0, quarantined: 0, skippedDemo: false };
    }
    let imported = 0, quarantined = 0, skippedDemo = false;
    const store = this.app.store;
    store.tx(() => {
      for (const op of raw.operations as OperationProfile[]) {
        if (op.id === DEMO_OPERATION_ID || op.code === 'OP-ARCTIC-DRAINER') { skippedDemo = true; continue; }
        if (store.getOperation(op.id)) continue;
        imported++;
        store.insertOperation({ ...op, code: store.getOperation(op.code) ? `${op.code}-V0` : op.code, isDemo: false, revision: 0, tags: ['imported-v0'] });
        const entityMap = new Map<string, string>();
        for (const e of (raw.entities ?? []).filter((x: Entity) => x.operationId === op.id) as Entity[]) {
          const canonical = canonicalize(e.type, e.value);
          const existing = store.findEntity(op.id, e.type, e.value);
          if (existing) { entityMap.set(e.id, existing.id); continue; }
          const ub = staticUbiquity(e.type, canonical, e.metadata ?? {});
          const id = store.getEntity(e.id) ? newId('ent', 10) : e.id;
          store.insertEntity({ ...e, id, canonical, value: canonical || e.value, depth: e.isSeed ? 0 : 1, ubiquity: ub.ubiquity, tags: ['imported-v0'], metadata: { ...(e.metadata ?? {}) } });
          entityMap.set(e.id, id);
        }
        for (const s of (raw.seeds ?? []).filter((x: Seed) => x.operationId === op.id) as Seed[]) {
          store.insertSeed({ ...s, id: store.get('SELECT id FROM seeds WHERE id=?', s.id) ? newId('seed', 8) : s.id, status: 'pending', source: 'imported-v0' });
        }
        const evidenceStatus = new Map<string, string>();
        for (const ev of (raw.evidence ?? []).filter((x: Evidence) => x.operationId === op.id) as Evidence[]) {
          const simulated = LEGACY_SIMULATED_PROVENANCE.has(ev.provenance);
          if (simulated) quarantined++;
          const id = store.getEvidenceById(ev.id) ? newId('ev', 10) : ev.id;
          evidenceStatus.set(ev.id, simulated ? 'invalidated' : ev.status);
          store.insertEvidence({
            ...ev, id, relatedEntityIds: (ev.relatedEntityIds ?? []).map(x => entityMap.get(x) ?? x), synthetic: simulated, assertion: simulated ? 'observed' : 'imported',
            status: simulated ? 'invalidated' : ev.status, invalidationReason: simulated ? QUARANTINE_REASON : ev.invalidationReason, collector: simulated ? 'legacy-simulator' : 'legacy-import', collectedAt: ev.timestamp,
          });
        }
        for (const rel of (raw.relationships ?? []).filter((x: Relationship) => x.operationId === op.id) as Relationship[]) {
          const src = entityMap.get(rel.sourceEntityId), dst = entityMap.get(rel.targetEntityId);
          if (!src || !dst) continue;
          const allSimulated = (rel.evidenceIds ?? []).length > 0 && rel.evidenceIds.every(id => evidenceStatus.get(id) === 'invalidated');
          if (store.findRelationship(op.id, src, dst, rel.type)) continue;
          store.upsertRelationshipRow({
            ...rel, id: newId('rel', 10), sourceEntityId: src, targetEntityId: dst, sources: ['legacy-import'], assertion: 'imported',
            ...(allSimulated ? { state: 'UNRESOLVED', confidence: 0.1, reasoning: `${rel.reasoning} [supported only by quarantined v0.x simulated data]` } : {}),
          });
        }
        // Entities supported only by quarantined evidence are marked unsupported (kept, never expanded).
        for (const [, id] of entityMap) {
          const ent = store.getEntity(id);
          if (!ent || ent.isSeed) continue;
          const evs = store.evidenceForEntity(id);
          if (evs.length && evs.every(e => e.status !== 'valid')) store.updateEntity({ ...ent, metadata: { ...ent.metadata, unsupported: true, unsupportedReason: 'Only supported by quarantined legacy simulated evidence' } });
        }
        for (const h of (raw.hypotheses ?? []).filter((x: Hypothesis) => x.operationId === op.id) as Hypothesis[]) store.saveHypothesis({ ...h, aiGenerated: false }, null);
        for (const l of (raw.leads ?? []).filter((x: Lead) => x.operationId === op.id) as Lead[]) store.saveLead({ ...l, source: 'legacy', key: `legacy:${l.id}` });
        for (const p of (raw.monitoringProbes ?? []).filter((x: MonitoringProbe) => x.operationId === op.id) as MonitoringProbe[]) store.saveMonitor({ ...p, status: 'PAUSED', notes: `${p.notes} (imported from v0.x — paused; re-enable after review)` });
        for (const r of (raw.reappearanceLeads ?? []).filter((x: ReappearanceLead) => x.operationId === op.id) as ReappearanceLead[]) store.saveReappearance({ ...r, source: 'legacy-v0' });
        for (const a of (raw.auditLogs ?? []).filter((x: any) => x.operationId === op.id)) store.run('INSERT OR IGNORE INTO audit_log (id, operation_id, action, details, timestamp) VALUES (?, ?, ?, ?, ?)', a.id, a.operationId, a.action, a.details, a.timestamp);
        store.addChange(op.id, 'migrated', `Imported from Operation Hunter v0.x. ${quarantined} simulated observations were quarantined.`);
      }
      store.setMeta('legacy_import_done', nowIso());
    });
    try {
      const backup = file.replace(/\.json$/, `.v0-backup-${Date.now()}.json`);
      fs.renameSync(file, backup);
      store.setMeta('legacy_backup_file', backup);
    } catch { /* read-only location: leave the file, import is already recorded */ }
    return { operations: imported, quarantined, skippedDemo };
  }
}

export function seedTypeToEntity(type: string): Entity['type'] {
  switch (type) {
    case 'template_fingerprint': return 'template';
    case 'domain': case 'wallet': case 'ip': case 'certificate': case 'identifier': case 'artifact': case 'contract': case 'nameserver': case 'email': case 'asn': case 'template': case 'hostname':
      return type as Entity['type'];
    default: return 'domain';
  }
}
