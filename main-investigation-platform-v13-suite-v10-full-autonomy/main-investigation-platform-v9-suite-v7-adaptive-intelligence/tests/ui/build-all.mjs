// Every real page, for the interaction sweep (tests/ui-click-all.py).
//
// tests/ui/build.mjs mounts the five tools through a hand-written route table. This build instead
// generates its route table from the real app/ tree: every app/**/page.tsx is imported as the page
// module Next would serve, dynamic segments ([id]) are matched and passed as `params`, and async
// pages are awaited. Pages that read the database on the server (app/investigations/[id]) are
// rendered in Node by the same page module against the test database (react-dom/server) and their
// client islands (AgentPanel) are mounted in the browser — the split Next itself makes.
//
// Served on the same origin as the API, only when the request carries the cookie `mip_ui=all`, so
// direct navigation and reloads of real paths behave as in the product.
import {existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';
import {build} from 'esbuild';
import {importFile, repoRoot} from '../lib/portable.mjs';
import {buildSuiteUi} from './build.mjs';

function pages(dir = join(repoRoot, 'app'), out = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) { if (n !== 'api') pages(p, out); }
    else if (n === 'page.tsx') out.push(p);
  }
  return out;
}
const routeOf = file => '/' + relative(join(repoRoot, 'app'), file).replace(/\\/g, '/').replace(/\/?page\.tsx$/, '');
const serverData = src => /getD1\s*\(|from ["']@\/lib\/(platform|planner|orchestrator)["']/.test(src);

export async function buildAllPagesUi(outDir) {
  mkdirSync(outDir, {recursive: true});
  const base = await buildSuiteUi(outDir);          // reuses its shims, icons and CSS; writes suite.css
  if (base.skipped) return base;
  const list = pages().map(file => ({file, route: routeOf(file), server: serverData(readFileSync(file, 'utf8'))}));
  const client = list.filter(p => !p.server), server = list.filter(p => p.server);
  const routesModule = `// generated by tests/ui/build-all.mjs
import { useEffect, useState, useRef, createElement } from "react";
import { createPortal } from "react-dom";
import { AutonomyInvestigation } from "@/components/suite/autonomy";
import { PlatformShell } from "@/components/platform-shell";
import { AgentPanel } from "@/components/agent-panel";
import { usePathname } from "next/navigation";
${client.map((p, i) => `import P${i} from ${JSON.stringify(p.file.replace(/\\/g, '/'))};`).join('\n')}
const ROUTES = [${client.map((p, i) => `[${JSON.stringify(p.route)}, P${i}]`).join(', ')}];
const SERVER = ${JSON.stringify(server.map(p => p.route))};
const toRe = r => new RegExp('^' + r.replace(/\\[\\.\\.\\.[^\\]]+\\]/g, '(.+)').replace(/\\[[^\\]]+\\]/g, '([^/]+)') + '/?$');
const names = r => [...r.matchAll(/\\[(?:\\.\\.\\.)?([^\\]]+)\\]/g)].map(m => m[1]);
function match(path) {
  for (const [route, Page] of ROUTES) { const m = path.match(toRe(route)); if (m) return {route, Page, params: Object.fromEntries(names(route).map((n, i) => [n, decodeURIComponent(m[i + 1])]))}; }
  for (const route of SERVER) { const m = path.match(toRe(route)); if (m) return {route, server: true}; }
  return null;
}
function ServerPage({path}) {
  const [html, setHtml] = useState(null), [islands, setIslands] = useState({}), [targets, setTargets] = useState({}), host = useRef(null);
  useEffect(() => { let live = true; fetch('/__ssr' + path).then(async r => { const j = await r.json(); if (live) { setHtml(j.html); setIslands({agent:j.agent, autonomy:j.autonomy}); } }); return () => { live = false; }; }, [path]);
  useEffect(() => { if(host.current) setTargets({agent:host.current.querySelector('[data-island="agent"]'),autonomy:host.current.querySelector('[data-island="autonomy"]')}); },[html]);
  if (html === null) return createElement('main', {className: 'page-wrap'}, 'Loading…');
  return createElement('div', null, createElement('div', {ref:host,dangerouslySetInnerHTML: {__html: html}}), islands.agent && targets.agent ? createPortal(createElement(AgentPanel,{investigationId:islands.agent}),targets.agent):null, islands.autonomy && targets.autonomy ? createPortal(createElement(AutonomyInvestigation,{id:islands.autonomy}),targets.autonomy):null);
}
function Resolved({Page, params}) {
  const [el, setEl] = useState(null), [err, setErr] = useState(null);
  useEffect(() => { let live = true; Promise.resolve(Page({params: Promise.resolve(params)})).then(x => live && setEl(x), e => live && setErr(e)); return () => { live = false; }; }, [Page, JSON.stringify(params)]);
  if (err) throw err;
  return el;
}
function Router() {
  const path = usePathname();
  const hit = match(path);
  if (!hit) return createElement('main', {className: 'page-wrap', 'data-not-found': path}, createElement('h1', null, '404 · This page could not be found.'));
  if (hit.server) return createElement(ServerPage, {path, key: path});
  const isAsync = hit.Page.constructor && hit.Page.constructor.name === 'AsyncFunction';
  return isAsync ? createElement(Resolved, {Page: hit.Page, params: hit.params, key: path}) : createElement(hit.Page, {params: Promise.resolve(hit.params)});
}
export const App = () => createElement(PlatformShell, null, createElement(Router));
`;
  writeFileSync(join(outDir, 'app-routes.tsx'), routesModule);
  // Browser: hydrate the server-rendered HTML (as a production Next page does); a mismatch or a
  // recoverable error is reported on the console, where the sweep fails on it.
  const entry = `import { createRoot, hydrateRoot } from "react-dom/client";
import { createElement } from "react";
import { App } from "./app-routes";
const root = document.getElementById("root");
if (root.hasChildNodes()) { window.__MIP_RENDER__ = "hydrate"; hydrateRoot(root, createElement(App), { onRecoverableError: (error) => console.error("Hydration error: " + (error && error.message || error)) }); }
else { window.__MIP_RENDER__ = "client"; createRoot(root).render(createElement(App)); }
`;
  // Node: the same tree rendered to HTML for a path, the way the production server renders client
  // components before hydration.
  writeFileSync(join(outDir, 'ssr-app.tsx'), `import { renderToString } from "react-dom/server";
import { createElement } from "react";
import { App } from "./app-routes";
export function renderApp(path) { globalThis.__SSR_PATH__ = path; try { return renderToString(createElement(App)); } finally { delete globalThis.__SSR_PATH__; } }
`);
  await bundle(join(outDir, 'ssr-app.tsx'), join(outDir, 'ssr', 'app.mjs'), 'node');
  const entryFile = join(outDir, 'entry-all.tsx');
  writeFileSync(entryFile, entry);
  await bundle(entryFile, join(outDir, 'all.js'), 'browser');
  // Server-rendered pages: the page module itself plus react-dom/server, bundled for Node against the
  // test D1 binding. Client islands (AgentPanel) are left out of the HTML and mounted by the browser.
  const ssr = [];
  for (const [i, p] of server.entries()) {
    const wrapper = join(outDir, `ssr-entry-${i}.tsx`);
    writeFileSync(wrapper, `import Page from ${JSON.stringify(p.file.replace(/\\/g, '/'))};
import { renderToString } from "react-dom/server";
import { createElement } from "react";
import { AgentPanel } from "@/components/agent-panel";
import { AutonomyInvestigation } from "@/components/suite/autonomy";
export async function render(params) {
  const tree = await Page({ params: Promise.resolve(params) });
  let agent = null, autonomy = null;
  const strip = node => {
    if (!node || typeof node !== "object") return node;
    if (Array.isArray(node)) return node.map(strip);
    if (node.type === AgentPanel) { agent = node.props.investigationId; return createElement("div",{"data-island":"agent"}); }
    if (node.type === AutonomyInvestigation) { autonomy=node.props.id; return createElement("div",{"data-island":"autonomy"}); }
    return node.props && node.props.children !== undefined ? { ...node, props: { ...node.props, children: strip(node.props.children) } } : node;
  };
  return { html: renderToString(createElement("div", null, strip(tree))), agent, autonomy };
}
`);
    const out = join(outDir, 'ssr', `page-${i}.mjs`);
    await bundle(wrapper, out, 'node');
    ssr.push({route: p.route, file: out});
  }
  writeFileSync(join(outDir, 'all.html'), '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Main Investigation Platform</title><link rel="icon" href="/favicon.svg"><link rel="stylesheet" href="/__ui/suite.css"></head><body class="antialiased"><div id="root"></div><script src="/__ui/all.js"></script></body></html>');
  return {dir: outDir, pages: list.map(p => p.route), ssr, app: join(outDir, 'ssr', 'app.mjs')};
}

// Same shims as tests/ui/build.mjs (next/link, next/navigation, lucide icons), reused through its
// esbuild options by building the suite bundle's plugin inline.
async function bundle(entry, outfile, platform) {
  const {nodePaths, plugin} = await shimPlugin();
  await build({
    entryPoints: [entry], bundle: true, format: platform === 'node' ? 'esm' : 'iife', platform, outfile,
    jsx: 'automatic', loader: {'.tsx': 'tsx', '.ts': 'ts'}, nodePaths, logLevel: 'error',
    define: {'process.env.NODE_ENV': '"production"'}, alias: {'@': repoRoot},
    ...(platform === 'node' ? {banner: {js: "import {createRequire as __cr} from 'node:module'; const require = __cr(import.meta.url);"}} : {}),
    plugins: [plugin],
  });
}

let cached;
async function shimPlugin() {
  if (cached) return cached;
  const {execSync} = await import('node:child_process');
  const nodePaths = [join(repoRoot, 'node_modules'), process.env.NODE_PATH, (() => { try { return execSync('npm root -g', {encoding: 'utf8'}).trim(); } catch { return ''; } })()]
    .filter(d => d && existsSync(join(d, 'react')) && existsSync(join(d, 'react-dom')));
  const icons = new Set();
  const walk = d => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else if (/\.tsx?$/.test(n)) for (const m of readFileSync(p, 'utf8').matchAll(/import\s*\{([^}]+)\}\s*from\s*["']lucide-react["']/g)) for (const part of m[1].split(',')) { const name = part.trim().split(/\s+as\s+/)[0].replace(/^type\s+/, ''); if (/^[A-Z]\w*$/.test(name)) icons.add(name); } } };
  walk(join(repoRoot, 'components')); walk(join(repoRoot, 'app'));
  const lucide = `import * as React from 'react';
const make=(name)=>function Icon({size=16,...rest}){return React.createElement('svg',{width:size,height:size,viewBox:'0 0 24 24',fill:'none',stroke:'currentColor',strokeWidth:2,'data-icon':name,'aria-hidden':'true',...rest},React.createElement('rect',{x:4,y:4,width:16,height:16,rx:4}));};
${[...icons].map(n => `export const ${n}=make(${JSON.stringify(n)});`).join('\n')}`;
  const resolveTs = b => { for (const ext of ['', '.tsx', '.ts', '/index.tsx', '/index.ts']) if (existsSync(b + ext) && statSync(b + ext).isFile()) return b + ext; return b; };
  cached = {nodePaths, plugin: {name: 'all-pages-shims', setup(p) {
    p.onResolve({filter: /^next\/(link|navigation)$/}, () => ({path: join(repoRoot, 'tests', 'ui', 'next-shim.tsx')}));
    p.onResolve({filter: /^lucide-react$/}, () => ({path: 'lucide', namespace: 'shim'}));
    p.onLoad({filter: /.*/, namespace: 'shim'}, () => ({contents: lucide, loader: 'js', resolveDir: repoRoot}));
    p.onResolve({filter: /\.css$/}, () => ({path: 'css', namespace: 'empty'}));
    p.onLoad({filter: /.*/, namespace: 'empty'}, () => ({contents: '', loader: 'js'}));
    p.onResolve({filter: /^cloudflare:workers$/}, () => ({path: 'env', namespace: 'cfenv'}));
    p.onLoad({filter: /.*/, namespace: 'cfenv'}, () => ({contents: 'export const env=new Proxy({},{get:(_,k)=>globalThis.__TEST_ENV[k],has:(_,k)=>k in globalThis.__TEST_ENV})', loader: 'js'}));
    p.onResolve({filter: /^@\//}, a => ({path: resolveTs(join(repoRoot, a.path.slice(2)))}));
  }}};
  return cached;
}

/** main-harness `extra` handler: the all-pages UI for requests carrying the cookie mip_ui=all. */
export async function serveAllPagesUi(built) {
  const ssr = await Promise.all(built.ssr.map(async s => ({...s, re: new RegExp('^' + s.route.replace(/\[[^\]]+\]/g, '([^/]+)') + '/?$'), names: [...s.route.matchAll(/\[([^\]]+)\]/g)].map(m => m[1]), mod: await importFile(s.file)})));
  const app = await importFile(built.app);
  return async (req, res, url) => {
    if (!/(?:^|;\s*)mip_ui=all(?:;|$)/.test(req.headers.cookie ?? '')) return false;
    if (url.pathname.startsWith('/__ui/')) {
      const file = join(built.dir, url.pathname.slice(6));
      if (!existsSync(file)) { res.writeHead(404); res.end(); return true; }
      res.writeHead(200, {'content-type': file.endsWith('.css') ? 'text/css' : 'text/javascript'}); res.end(readFileSync(file)); return true;
    }
    if (url.pathname.startsWith('/__ssr/')) {
      const path = url.pathname.slice(6);
      for (const s of ssr) {
        const m = path.match(s.re);
        if (!m) continue;
        const params = Object.fromEntries(s.names.map((n, i) => [n, decodeURIComponent(m[i + 1])]));
        try {
          const {html, agent} = await s.mod.render(params);
          res.writeHead(200, {'content-type': 'application/json'}); res.end(JSON.stringify({html, agent}));
        } catch (err) {
          res.writeHead(500, {'content-type': 'application/json'}); res.end(JSON.stringify({error: String(err?.stack ?? err)}));
        }
        return true;
      }
      res.writeHead(404); res.end(); return true;
    }
    if (req.method === 'GET' && !url.pathname.includes('.')) {
      let html;
      try { html = app.renderApp(url.pathname); } catch (err) {
        res.writeHead(500, {'content-type': 'text/plain'}); res.end(`server render failed for ${url.pathname}: ${err?.stack ?? err}`); return true;
      }
      res.writeHead(200, {'content-type': 'text/html'});
      res.end(readFileSync(join(built.dir, 'all.html'), 'utf8').replace('<div id="root"></div>', `<div id="root">${html}</div>`));
      return true;
    }
    if (url.pathname === '/favicon.svg' && existsSync(join(repoRoot, 'public', 'favicon.svg'))) { res.writeHead(200, {'content-type': 'image/svg+xml'}); res.end(readFileSync(join(repoRoot, 'public', 'favicon.svg'))); return true; }
    return false;
  };
}
