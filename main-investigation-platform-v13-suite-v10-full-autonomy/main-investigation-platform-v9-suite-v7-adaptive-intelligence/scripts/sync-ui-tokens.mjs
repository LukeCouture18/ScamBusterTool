const block = css => `/* ${START} (${NOTE}) */\n${css}\n/* ${END} */`;
const MARKED = new RegExp(`/\\* ${START}[\\s\\S]*?${END} \\*/`);

export function render(target, source) {
  const b = block(target.css);
  if (MARKED.test(source)) return source.replace(MARKED, b);
  if (target.where === 'style') {
    const i = source.indexOf('</style>');
    if (i < 0) throw new Error(`${target.file}: no <style> element`);
    return `${source.slice(0, i)}\n${b}\n${source.slice(i)}`;
  }
  if (target.where === 'after-tailwind') {
    const m = source.match(/@import\s+["']tailwindcss["'];?\s*\n?/);
    if (!m) throw new Error(`${target.file}: no @import "tailwindcss"`);
    const at = m.index + m[0].length;
    return `${source.slice(0, at)}${source.slice(0, at).endsWith('\n') ? '' : '\n'}${b}\n${source.slice(at)}`;
  }
  return `${source.replace(/\s*$/, '')}\n\n${b}\n`;
}

export function run({check = false} = {}) {
  const out = [];
  for (const target of targets()) {
    if (!existsSync(target.file)) { out.push({tool: target.tool, state: 'missing file', file: target.file}); continue; }
    const before = readFileSync(target.file, 'utf8');
    const after = render(target, before);
    const state = before === after ? 'in sync' : check ? 'out of date' : 'updated';
    if (!check && before !== after) writeFileSync(target.file, after);
    out.push({tool: target.tool, state, file: relative(root, target.file)});
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const result = run({check});
  for (const r of result) console.log(`${r.state.padEnd(12)} ${r.tool}  (${r.file})`);
  if (check && result.some(r => r.state !== 'in sync')) { console.error('UI tokens are out of date: run node scripts/sync-ui-tokens.mjs'); process.exit(1); }
}
