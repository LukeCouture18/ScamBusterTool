#!/usr/bin/env node
// One visual language for every tool: copies the design tokens of sdk/ui/suite.css (the --mip-*
// custom properties) into each tool's own screens and maps that tool's existing color variables
// onto them, so the Site Finder review page, the Site Investigator page, the Wallet Investigator
// and Form Submitter apps, the Wallet Logger extension and Operation Hunter all use Main's dark
// navy palette. Only colors change: layouts, class names and element ids are untouched, so the
// tools' own browser tests keep working.
//
// Each target gets one generated block between markers; everything outside the markers is the
// tool's own. Run after editing sdk/ui/suite.css:
//     node scripts/sync-ui-tokens.mjs            write the blocks
//     node scripts/sync-ui-tokens.mjs --check    exit 1 if any block is missing or out of date
// Operation Hunter lives beside Main; it is found at HUNTER_DIR or as a sibling folder and skipped
// when absent.
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const START = 'mip-theme:start';
const END = 'mip-theme:end';
const NOTE = 'generated by scripts/sync-ui-tokens.mjs from sdk/ui/suite.css; edit that file, not this block';

export function tokens() {
  const css = readFileSync(join(root, 'sdk', 'ui', 'suite.css'), 'utf8');
  const m = css.match(/:root\s*\{([^}]*)\}/);
  if (!m) throw new Error('sdk/ui/suite.css has no :root token block');
  const vars = Object.fromEntries([...m[1].matchAll(/(--mip-[\w-]+)\s*:\s*([^;]+);/g)].map(x => [x[1], x[2].trim()]));
  return vars;
}
const tokenRule = (t, selector = ':root') => `${selector}{${Object.entries(t).map(([k, v]) => `${k}:${v}`).join(';')}}`;

function hunterDir() {
  const sibs = (() => { try { return readdirSync(join(root, '..')).map(n => join(root, '..', n)); } catch { return []; } })();
  return [process.env.HUNTER_DIR, ...['operation-hunter', 'operation-hunter-v2.0', 'hunter'].map(n => join(root, '..', n)), ...sibs]
    .filter(Boolean).map(p => resolve(p)).find(p => existsSync(join(p, 'src', 'v1', 'suite.css')) && existsSync(join(p, 'server', 'integration', 'worker.ts')));
}

